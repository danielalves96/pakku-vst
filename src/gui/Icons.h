    /** The parsed path, cached the first time it is asked for. */
    inline const juce::Path& path (Id id)
    {
        static std::array<juce::Path, (size_t) Id::count> cache;
        static std::array<bool, (size_t) Id::count> ready {};

        auto& p = cache[(size_t) id];
        if (! ready[(size_t) id])
        {
            p = juce::Drawable::parseSVGPath (svgPath (id));
            ready[(size_t) id] = true;
        }
        return p;
    }

    /** Drawable form, for where JUCE insists on one (menu items). */
    inline std::unique_ptr<juce::Drawable> drawable (Id id, juce::Colour colour)
    {
        auto d = std::make_unique<juce::DrawablePath>();
        d->setPath (path (id));
        d->setFill (colour);
        return d;
    }

    /** Draws centred in the area, aspect preserved. */
    inline void draw (juce::Graphics& g, Id id, juce::Rectangle<float> area,
                      juce::Colour colour)
    {
        const auto& p = path (id);
        if (p.isEmpty()) return;

        g.setColour (colour);
        g.fillPath (p, p.getTransformToScaleToFit (area, true));
    }
